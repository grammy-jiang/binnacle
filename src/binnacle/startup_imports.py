"""Import every runtime binnacle module once, at process start.

A serving process shares its checkout and virtual environment with later
deploys; a module it imports lazily after a checkout sync comes from the new
revision while the rest of the process runs the old one
(OPS-FOLLOWUP-shared-venv-lazy-import, R-M1-X1). Importing the runtime tree at
start closes that window. docs/startup-imports.md holds the full contract:
the fail-fast policy (exit ``EX_STARTUP_IMPORT``), the durable record that
only the real entry points write and clear, and the pinned sets.

The server's REQUIRED set is the frozen literal ``SERVER_MODULES`` of
``binnacle.startup_server_modules``, generated by
``scripts/gen_startup_server_modules.py`` and held to the walk of the binnacle
package by a drift test; the runtime imports exactly those names and never
walks the installed package directory (SD-90). A job manager imports
the pinned ``MANAGER_MODULES`` instead (E1B-R1). ``OPTIONAL_MODULES`` is the
pinned allowlist of modules that may fail; it is empty. E1 covers binnacle.*
only. The failure log line is one ``event=startup_import_failed`` line without
the message text.
"""

